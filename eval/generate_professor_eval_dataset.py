def build_dataset() -> list[dict[str, Any]]:
    if len(SCENARIOS) != 30:
        raise ValueError(f"Expected 30 scenarios, found {len(SCENARIOS)}")
    category_counts = Counter(row["scenario_category"] for row in SCENARIOS)
    if len(category_counts) != 5 or set(category_counts.values()) != {6}:
        raise ValueError(f"Expected 5 balanced categories (6 each): {category_counts}")
    requests = [row["question"].strip() for row in SCENARIOS]
    if len(requests) != len(set(requests)):
        raise ValueError("Instructor requests must be unique")

    dataset = []
    for index, scenario in enumerate(SCENARIOS, start=1):
        reference = {
            "expected_findings": scenario["expected_findings"],
            "expected_recommendations": scenario["expected_recommendations"],
            "keywords": scenario["keywords"],
            "limitations": [
                "학생 질문은 합성 시나리오이며 실제 수강생의 빈도·대표성을 나타내지 않음",
                "질문에 없는 강의 정책·성적·학생 특성은 추론하지 않음",
            ],
        }
        dataset.append({
            "question_id": f"P{index:03d}",
            "role": "professor",
            "task_type": scenario["task_type"],
            "data_origin": "synthetic_instructor_support_scenario",
            "course_name": scenario["course_name"],
            "scenario_theme": scenario["scenario_theme"],
            "student_questions": scenario["student_questions"],
            "question": scenario["question"],
            "ground_truth": json.dumps(reference, ensure_ascii=False),
            "evaluation_criteria": EVALUATION_CRITERIA,
            "scenario_category": scenario["scenario_category"],
            "review_status": "needs_faculty_review",
            "reviewer_id": "",
            "reviewed_at": "",
            "knowledge_scope": "제공된 합성 학생 질문만 근거로 사용; 실제 학생의 빈도·대표성 및 미기재 강의 정책은 추정하지 않음",
            "source_verification": "synthetic_scenario; faculty review required before paper analysis",
            "dataset_version": "professor_eval_v3_draft",
            "train_eval_overlap_status": "needs_manual_train_eval_overlap_audit",
            "models": {
                "Base Model": "",
                "Base Model + Student LoRA": "",
                "Base Model + Professor LoRA": "",
            },
            "contexts": {
                "Base Model": [],
                "Base Model + Student LoRA": [],
                "Base Model + Professor LoRA": [],
            },
            "generation_latency_s": {},
            "served_model_names": {},
        })
    return dataset


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate the professor evaluation dataset (30 synthetic teaching-support scenarios).")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).parent / "professor_eval_dataset_v3.json",
        help="Output JSON path (default: eval/professor_eval_dataset_v3.json)",
    )
    args = parser.parse_args()
    dataset = build_dataset()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(dataset, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    counts = Counter(item["scenario_category"] for item in dataset)
    print(f"Wrote {len(dataset)} professor scenarios to {args.output}")
    print("Category counts:", dict(counts))


if __name__ == "__main__":
    main()
