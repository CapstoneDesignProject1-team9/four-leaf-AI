"""PostgreSQL persistence for student chat questions and the tutor's answers.

Rows older than CHAT_LOG_RETENTION_MONTHS are deleted on startup, before advisor
queries, and at most once an hour while new questions arrive.
"""

from __future__ import annotations

import json
import logging
import time
from dataclasses import dataclass
from datetime import datetime

import psycopg

from app.core.config import settings

logger = logging.getLogger(__name__)
_PURGE_INTERVAL_S = 3600.0
_last_purge = 0.0


@dataclass(frozen=True)
class StoredQuestion:
    id: int
    question: str
    answer: str | None
    created_at: datetime


def _connect() -> psycopg.Connection:
    return psycopg.connect(
        host=settings.DB_HOST,
        port=settings.DB_PORT,
        dbname=settings.DB_NAME,
        user=settings.DB_USER,
        password=settings.DB_PASSWORD,
        connect_timeout=10,
    )


def initialize_chat_log_store() -> None:
    """Create the table, copy questions from the legacy table once, and purge old rows."""
    with _connect() as connection:
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS chat_logs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                session_id TEXT,
                question TEXT NOT NULL,
                answer TEXT,
                model_name TEXT,
                sources JSONB NOT NULL DEFAULT '[]'::jsonb,
                status TEXT NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending', 'answered', 'failed', 'legacy')),
                error TEXT,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                answered_at TIMESTAMPTZ
            )
            """
        )
        connection.execute(
            "CREATE INDEX IF NOT EXISTS idx_chat_logs_created_at ON chat_logs(created_at)"
        )
        # Questions saved before answers were stored keep their original timestamps.
        legacy = connection.execute("SELECT to_regclass('public.student_questions')").fetchone()
        empty = connection.execute("SELECT NOT EXISTS (SELECT 1 FROM chat_logs)").fetchone()
        if legacy and legacy[0] and empty and empty[0]:
            copied = connection.execute(
                """
                INSERT INTO chat_logs(session_id, question, status, created_at)
                SELECT session_id, message, 'legacy', created_at FROM student_questions
                """
            ).rowcount
            logger.info("기존 student_questions %s건을 chat_logs로 옮겼습니다.", copied)
    purge_expired_chat_logs()


def purge_expired_chat_logs() -> int:
    """Delete rows past the retention period and return how many were removed."""
    global _last_purge
    with _connect() as connection:
        deleted = connection.execute(
            "DELETE FROM chat_logs WHERE created_at < now() - make_interval(months => %s)",
            (settings.CHAT_LOG_RETENTION_MONTHS,),
        ).rowcount
    _last_purge = time.monotonic()
    if deleted:
        logger.info("보관 기간이 지난 대화 기록 %s건을 삭제했습니다.", deleted)
    return deleted


def create_chat_log(*, question: str, session_id: str | None) -> int:
    """Store the question before the answer is generated and return its row id."""
    if time.monotonic() - _last_purge > _PURGE_INTERVAL_S:
        try:
            purge_expired_chat_logs()
        except Exception:
            logger.exception("보관 기간 만료 기록 삭제 실패")
    with _connect() as connection:
        row = connection.execute(
            "INSERT INTO chat_logs(question, session_id) VALUES (%s, %s) RETURNING id",
            (question.strip(), session_id),
        ).fetchone()
    assert row is not None
    return int(row[0])


def complete_chat_log(
    log_id: int, *, answer: str, model_name: str | None, sources: list[str]
) -> None:
    with _connect() as connection:
        connection.execute(
            """
            UPDATE chat_logs
            SET answer = %s, model_name = %s, sources = %s::jsonb,
                status = 'answered', answered_at = CURRENT_TIMESTAMP
            WHERE id = %s
            """,
            (answer, model_name, json.dumps(sources, ensure_ascii=False), log_id),
        )


def fail_chat_log(log_id: int, *, error: str) -> None:
    with _connect() as connection:
        connection.execute(
            "UPDATE chat_logs SET status = 'failed', error = %s WHERE id = %s",
            (error[:1000], log_id),
        )


def fetch_recent_questions(*, days: int | None, limit: int) -> list[StoredQuestion]:
    """Return up to `limit` of the newest questions, optionally within the last `days` days."""
    query = "SELECT id, question, answer, created_at FROM chat_logs"
    params: list[object] = []
    if days is not None:
        query += " WHERE created_at >= now() - make_interval(days => %s)"
        params.append(days)
    query += " ORDER BY created_at DESC, id DESC LIMIT %s"
    params.append(limit)
    with _connect() as connection:
        rows = connection.execute(query, params).fetchall()
    return [StoredQuestion(int(r[0]), r[1], r[2], r[3]) for r in rows]
